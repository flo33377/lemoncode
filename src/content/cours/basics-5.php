<h1>Analyser du code avec la Dev Tools</h1>

<p>
Les boîte à outils pour les développeurs, communément appelés "Dev Tools", sont un 
ensemble d'outils très utiles pour analyser du code front, le comprendre, le modifier ou 
encore débeuger.<br>
Ici, on utilisera la Dev Tools du navigateur Chrome, que j'utilise majoritairement, mais 
sachez que ces outils existent pour différents navigateurs, en fonction de ce que vous utilisez.
<br><br>
Pour ouvrir la Dev Tools de Chrome, rendez-vous su n'importe quelle page web, faites clic droit 
et cliquez sur "Inspecter" : un volet à droite va s'ouvrir.
</p>

